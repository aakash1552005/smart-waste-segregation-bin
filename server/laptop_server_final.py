"""
============================================================
 AI-BASED SMART GARBAGE SEGREGATION BIN
 Laptop Inference Server — Final Version
============================================================
 SETUP (run once):
   pip install flask tensorflow pillow numpy

 HOW TO RUN:
   1. Put waste_classifier.h5 and class_names.json in this folder
   2. Find your laptop IP:
      Windows  → ipconfig  → IPv4 Address
      Mac/Linux→ ifconfig  → inet
   3. Update SERVER_URL in esp32cam_final.ino with that IP
   4. python laptop_server.py
   5. Keep this running while the bin is in use

 CONFIDENCE THRESHOLD:
   If model confidence < 60% → returns "9" to ESP32-CAM
   ESP32-CAM forwards "9" to Arduino → Arduino uses sensor fallback
   This prevents wrong bin selections on blurry/ambiguous images
============================================================
"""

from flask import Flask, request
import numpy as np
from PIL import Image
import io, os, json
import tensorflow as tf

app = Flask(__name__)

# ─── Load class names from JSON (generated by Colab notebook) ─
with open("class_names.json") as f:
    CATEGORIES = json.load(f)
# CATEGORIES = ["wet", "dry", "plastic", "biomedical", "recyclable"]

print(f"[SERVER] Categories  : {CATEGORIES}")
print(f"[SERVER] Index map   : {dict(enumerate(CATEGORIES))}")

# ─── Model settings ───────────────────────────────────────────
IMG_SIZE          = (224, 224)
CONFIDENCE_THRESHOLD = 0.60      # below 60% → return '9' (sensor fallback)
MODEL_PATH        = "waste_classifier.h5"

# ─── Load model ───────────────────────────────────────────────
print(f"[SERVER] Loading {MODEL_PATH} ...")
if not os.path.exists(MODEL_PATH):
    print("[ERROR] waste_classifier.h5 not found!")
    print("        Download it from Colab (Cell 15) and place here.")
    model = None
else:
    model = tf.keras.models.load_model(MODEL_PATH)
    print(f"[SERVER] Model loaded  : input={model.input_shape}  output={model.output_shape}")

print(f"[SERVER] Confidence threshold : {CONFIDENCE_THRESHOLD*100:.0f}%")
print(f"[SERVER] Starting on http://0.0.0.0:5000  — waiting for ESP32-CAM...\n")
print("=" * 55)


# ─── Main classification endpoint ─────────────────────────────
@app.route("/classify", methods=["POST"])
def classify():
    """
    Receives raw JPEG bytes from ESP32-CAM.
    Returns:
      "0" = wet
      "1" = dry
      "2" = plastic
      "3" = biomedical
      "4" = recyclable
      "9" = low confidence → Arduino will use sensor fallback
    """
    try:
        # ── Read and decode JPEG ─────────────────────────────
        img_bytes = request.data
        if not img_bytes or len(img_bytes) < 100:
            return "9", 200

        img = Image.open(io.BytesIO(img_bytes)).convert("RGB")
        img = img.resize(IMG_SIZE)

        # Save last image for debugging (optional, comment out if not needed)
        img.save("last_capture.jpg")

        # ── Run inference ────────────────────────────────────
        if model is None:
            print("[ERROR] No model loaded — returning fallback")
            return "9", 200

        arr  = np.array(img, dtype=np.float32) / 255.0
        arr  = np.expand_dims(arr, axis=0)
        pred = model.predict(arr, verbose=0)[0]

        category_idx = int(np.argmax(pred))
        confidence   = float(np.max(pred))
        category_name = CATEGORIES[category_idx]

        # ── Confidence check ─────────────────────────────────
        if confidence < CONFIDENCE_THRESHOLD:
            print(f"[LOW CONF] {category_name.upper()} {confidence*100:.1f}% "
                  f"< {CONFIDENCE_THRESHOLD*100:.0f}% → fallback (9)")
            return "9", 200

        # ── All good — return category ────────────────────────
        print(f"[CLASSIFY] → {category_name.upper():12s} "
              f"confidence={confidence*100:.1f}%  "
              f"(index={category_idx})")

        # Print probability bar for all classes
        bars = ""
        for i, (cat, prob) in enumerate(zip(CATEGORIES, pred)):
            marker = " ◄" if i == category_idx else ""
            bars += f"   {cat:12s} : {'█'*int(prob*20):<20s} {prob*100:5.1f}%{marker}\n"
        print(bars)

        return str(category_idx), 200

    except Exception as e:
        print(f"[ERROR] {e}")
        return "9", 200


# ─── Health check ─────────────────────────────────────────────
@app.route("/health", methods=["GET"])
def health():
    status = "OK" if model else "NO_MODEL"
    return status, 200


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=5000, debug=False)
